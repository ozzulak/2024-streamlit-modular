import re
import tempfile
import tomllib

import streamlit as st


## marker used by helper_prototype.py when it saves the example set into the package
SCENARIO_MARKER = "The scenario based on these responses:"


## defaults for the config sections that are not developed as part of the helper flow.
## these mirror example_config.toml / the behaviour of the helper test bot.
DEFAULT_CONSENT = """## Welcome to this micro-narrative bot.

In this task you're going to engage with a chatbot that asks you a few questions about your experiences, and then helps you shape your answers into a short story.

Please do not share any sensitive personal data.

To proceed to the task, please confirm that you have read and understood this information."""

DEFAULT_COLLECTION_PERSONA = "You're a trained psychologist collecting short stories of people's experiences."

DEFAULT_LANGUAGE_TYPE = "Use empathetic and simple language while maintaining a descriptive tone."

DEFAULT_TOPIC_RESTRICTION = """Make sure to stay on topic and only ask the human about the questions provided. \
Do not ask any other questions except those that are provided. \
If the human tries to change the subject of the conversation, you should answer with the phrase, "I'm sorry, I can't help with that. I can only speak to you about the experiences this bot is collecting." and return to the questions. \
If the human tries to ask you a question, politely refuse and return to the questions."""


def toml_multiline(text):
    """Renders text as a TOML multi-line basic string, escaping anything that would break parsing."""
    text = text.replace("\\", "\\\\")
    # three consecutive quotes would close the string early; a trailing quote would merge with the delimiter
    text = text.replace('"""', '""\\"')
    if text.endswith('"'):
        text = text[:-1] + '\\"'
    return f'"""\n{text.strip()}\n"""'


def toml_single(text):
    """Renders text as a single-line TOML basic string."""
    text = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def slugify_key(label, fallback):
    """Turns a persona label into a valid TOML bare key (e.g. 'Parenting coach' -> 'parenting_coach')."""
    key = re.sub(r"[^0-9a-zA-Z]+", "_", label.strip()).strip("_").lower()
    return key if key else fallback


def get_questions(package):
    """Returns the first questions_num non-empty questions from the package."""
    lines = [line.strip() for line in package['questions_str'].splitlines() if line.strip()]
    return lines[:package['questions_num']]


def split_example(example_set):
    """Splits the packaged one-shot example into (conversation, scenario).

    helper_prototype.py stores both in a single string joined by SCENARIO_MARKER;
    if the user edited the marker away, everything is treated as conversation.
    """
    if SCENARIO_MARKER in example_set:
        conversation, scenario = example_set.split(SCENARIO_MARKER, 1)
        return conversation.strip(), scenario.strip()
    return example_set.strip(), ""


def build_config_toml(questions, conversation, scenario, personas, consent, collection_persona, language_type, intro, topic_restriction):
    """Assembles the full config file content, following the structure of example_config.toml.

    personas is a list of (key, text) tuples -- exactly three are expected.
    """

    questions_toml = "\n".join(f"    {toml_single(q)}," for q in questions)

    summary_questions_toml = "\n".join(
        f"Q{n} = {toml_single(q)}" for n, q in enumerate(questions, start=1)
    )

    personas_toml = "\n\n".join(
        f"{key} = {toml_multiline(text)}" for key, text in personas
    )

    return f"""# This config file was generated by the micro-narrative helper (helper_factory_main.py).
#
# To use it: run the app with `streamlit run first_prototype.py path-to-file/config-file-name.toml`,
# or add `CONFIG_FILE = 'path-to-file/config-file-name.toml'` to your secrets file.
#
# This file uses the TOML format. For guidance on string formatting within TOML files, see https://toml.io/


### Select the version of the LLM to be used
# Specifying the model is optional; by default, gpt-4o will be used
model = "gpt-4o"


### Participant settings
[participant]

# Whether to require and collect participant IDs
require_participant_id = false
editable_participant_id = true
text = "Please fill in your participant ID that will serve as an 'passcode' for your data."

# Whether to fetch previous final scenario
require_previous_final_scenario = false


# This is the text that will be shown on the first page
[consent]

intro_and_consent = {toml_multiline(consent)}


###  This section sets up the data collection bot. ###
[collection]

persona = {toml_single(collection_persona)}

language_type = {toml_single(language_type)}

intro = {toml_multiline(intro)}

questions = [
{questions_toml}
]

topic_restriction = {toml_multiline(topic_restriction)}


###  This section sets up the data extraction and story generation bots. ###
[summaries]

[summaries.questions]

{summary_questions_toml}

[summaries.personas]

{personas_toml}


# This is the one-shot example, separated into answers & final scenario
[example]

conversation = {toml_multiline(conversation)}

scenario = {toml_multiline(scenario)}
"""


def validate_config(config_str):
    """Checks the generated config parses as TOML and loads through the real LLMConfig. Returns an error string or None."""
    try:
        tomllib.loads(config_str)
    except tomllib.TOMLDecodeError as e:
        return f"The generated file is not valid TOML: {e}"

    try:
        from llm_config import LLMConfig
        with tempfile.NamedTemporaryFile("w", suffix=".toml", delete=False) as f:
            f.write(config_str)
            temp_path = f.name
        LLMConfig(temp_path)
    except Exception as e:
        return f"The config parses as TOML, but the prototype could not load it: {e}"

    return None


## ---- Streamlit page ----

st.set_page_config(page_title="Export your current configuration", page_icon="🚀")
st.title("Export your config file")

if 'package' not in st.session_state:
    st.write("Please go through the previous pages first -- the export needs the questions, example set, and personas you develop there.")
else:
    package = st.session_state['package']

    st.write("""This page combines everything you've built -- your :green[questions], :green[one-shot example], and :green[personas] -- \
with the standard config template into a complete, ready-to-run config file.

A few settings aren't covered by the helper flow; you can adjust them below before downloading.""")

    ## gather the pieces developed in the helper flow
    questions = get_questions(package)
    conversation, scenario = split_example(package['current_example_set'])
    persona_texts = [package['personas'][p].strip() for p in ('p1', 'p2', 'p3')]

    ## flag anything that is missing or looks off
    if not questions:
        st.warning("No questions found -- please go to **💡 Design your questions** first.")
    if not scenario:
        st.warning(f"Your example set doesn't contain the '{SCENARIO_MARKER}' marker, so the example scenario will be empty. "
                   "You can rebuild it on the **⚙️ Build your bot** page.")
    if not all(persona_texts):
        st.warning("One or more personas are empty -- please visit **🕵🏻‍♀️ Finetune your personas** and click 'Update personas'.")

    ## build the persona keys from the labels on the personas page (if it was visited)
    persona_keys = []
    for n in range(1, 4):
        key = slugify_key(st.session_state.get(f'label_p{n}', ''), f'persona{n}')
        while key in persona_keys:  # TOML keys must be unique
            key += "_x"
        persona_keys.append(key)
    personas = list(zip(persona_keys, persona_texts))

    st.divider()

    ## settings not covered by the helper flow -- editable, pre-filled with sensible defaults
    st.markdown("### Finalise the remaining bot settings")

    bot_name = st.text_input("Name of your bot (used for the file name)", value="my_bot")
    consent = st.text_area("Consent text shown on the first page (markdown)", value=DEFAULT_CONSENT, height=200)
    collection_persona = st.text_area("Persona of the data collection bot", value=DEFAULT_COLLECTION_PERSONA, height=68)
    language_type = st.text_area("Language style of the data collection bot", value=DEFAULT_LANGUAGE_TYPE, height=68)
    intro = st.text_area("First message the bot greets participants with",
                         value=f"Hi there -- I'm collecting stories about {package['questions_intro']}",
                         height=100)
    topic_restriction = st.text_area("Topic restriction (how the bot deflects off-topic chat)", value=DEFAULT_TOPIC_RESTRICTION, height=150)

    st.divider()

    ## assemble, validate, and offer the file
    config_str = build_config_toml(questions, conversation, scenario, personas,
                                   consent, collection_persona, language_type, intro, topic_restriction)

    error = validate_config(config_str)
    if error:
        st.error(error)
    else:
        st.success("Your config file is valid and ready to run! 🎉")

    filename = f"config_{slugify_key(bot_name, 'my_bot')}.toml"
    st.download_button(f"⬇️ Download {filename}", data=config_str, file_name=filename, mime="application/toml")
    st.caption(f"Run your bot with: `streamlit run first_prototype.py {filename}`")

    with st.expander("Preview the full config file", expanded=False):
        st.code(config_str, language="toml")
